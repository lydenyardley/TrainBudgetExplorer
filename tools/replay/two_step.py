"""Two tests that had to be cut in half.

Most tests changed once, and `split_by_test.py` puts each in the commit whose
change it covers. Two of them assert on two changes at once: one reads the
fare-type cell and the sentence in the panel that cell opens, and one reads the
count line and the shortlist chip. Their final form cannot pass until both
changes have landed, so each is written in two steps: the assertions this
change answers, and the rest.

The cut is named by the comment that introduces the later assertion rather than
by pasting two long versions of a test, because a paste is a thing that rots.

    python tools/replay/two_step.py
"""

import ast
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ROOT = Path(__file__).resolve().parent.parent.parent
CACHE = Path(__file__).resolve().parent
TARGET = "tests/test_build_demo_page.py"
BASE = "7b03c17"  # the commit before the first group landed
FINISHED = "eea30b6"  # the tip of the pass, which the split reads as "after"
NL = chr(10)

METHOD = re.compile(r"^    def (test_\w+)", re.M)

# test -> (line the later change's assertions start at, line they end before,
#          the group that answers them)
CUTS = {
    "test_result_changes_and_mobile_cells_are_accessible": (
        "        # C07: the condition is still on the same row",
        None,
        "railcard",
    ),
    "test_the_count_line_names_the_mix_and_what_the_party_is_two_of": (
        "        # A price with no ticket beside it",
        "        # The set names itself above the table",
        "shortlist",
    ),
}

# The middle step of the row-controls test, written out because the change that
# splits it moves a function name the test splits on, and no pair of markers
# can say that. Between the two steps the row keeps the shortlist toggle, which
# the shortlist change is what removes.
ROW_MID_EDITS = [
    (
        '        actions = script.split("function rowActions")[1]'
        '.split("function showRailcardDetails")[0]',
        '        actions = script.split("function rowActions")[1]'
        '.split("function cardNote")[0]',
    ),
    ('        self.assertIn(\'cardDetails.textContent = "Card details"\', actions)' + NL, ""),
]


def methods(text: str) -> dict[str, str]:
    starts = [(m.start(), m.group(1)) for m in METHOD.finditer(text)]
    return {
        name: text[start : starts[i + 1][0] if i + 1 < len(starts) else len(text)].rstrip(NL)
        for i, (start, name) in enumerate(starts)
    }


def from_git(rev: str) -> str:
    out = subprocess.run(
        ["git", "show", f"{rev}:{TARGET}"], cwd=ROOT, capture_output=True,
        text=True, encoding="utf-8", check=True,
    ).stdout
    return out.replace("\r\n", NL)


def emit(path: Path, pairs: list[tuple[str, str]]) -> None:
    body = ""
    for old, new in pairs:
        body += "        (" + NL
        body += "            " + repr(old) + "," + NL
        body += "            " + repr(new) + "," + NL
        body += "        )," + NL
    header = (
        '"""A step of a test that two changes answer between them.' + NL + NL
        + "Generated by two_step.py. Each step is a whole test, so a step that" + NL
        + "stops matching is a step applied out of order rather than a test that" + NL
        + "changed shape." + NL + '"""' + NL + NL
        + "import sys" + NL
        + "from pathlib import Path" + NL + NL
        + "sys.path.insert(0, str(Path(__file__).resolve().parent))" + NL
        + "from patch import patch  # noqa: E402" + NL + NL
        + "patch(" + NL
        + '    "' + TARGET + '",' + NL
        + "    [" + NL
    )
    path.write_text(header + body + "    ]," + NL + ")" + NL, encoding="utf-8", newline="")
    ast.parse(path.read_text(encoding="utf-8"))
    print("wrote", path.name, "with", len(pairs), "test(s)")


def main() -> int:
    before = methods(from_git(BASE))
    after = methods(from_git(FINISHED))

    early: list[tuple[str, str]] = []
    later: dict[str, list[tuple[str, str]]] = {}
    for name, (start_line, end_line, group) in CUTS.items():
        new = after[name]
        start = new.index(start_line)
        end = new.index(end_line) if end_line else len(new)
        head = new[:start].rstrip(NL)
        early.append((before[name], head))
        later.setdefault(group, []).append((head, new.rstrip(NL)))

    name = "test_the_row_keeps_the_action_and_the_panel_holds_the_rest"
    mid = before[name]
    for old_line, new_line in ROW_MID_EDITS:
        assert mid.count(old_line) == 1, old_line
        mid = mid.replace(old_line, new_line)
    early.append((before[name], mid))
    later.setdefault("shortlist", []).append((mid, after[name].rstrip(NL)))
    emit(CACHE / "tg_columns_mid.py", early)
    for group, pairs in later.items():
        emit(CACHE / f"tg_{group}_late.py", pairs)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
